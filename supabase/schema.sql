select
  users.id,
  coalesce(users.raw_user_meta_data->>'full_name', users.email, 'Usuario'),
  users.email,
  coalesce(users.raw_user_meta_data->>'full_name', users.email, 'Usuario'),
  coalesce(users.raw_user_meta_data->>'role', 'Comercial'),
  coalesce((users.raw_user_meta_data->>'can_view_dashboard')::boolean, false)
from auth.users users
on conflict (id) do update
set name = coalesce(public.profiles.name, excluded.name),
    email = excluded.email,
    full_name = coalesce(public.profiles.full_name, excluded.full_name),
    role = coalesce(public.profiles.role, excluded.role),
    can_view_dashboard = public.profiles.can_view_dashboard or excluded.can_view_dashboard;

