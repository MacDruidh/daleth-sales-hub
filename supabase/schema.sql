create or replace function create_profile_for_auth_user()
returns trigger as $$
begin
  insert into public.profiles (id, name, email, full_name, role, can_view_dashboard)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'full_name', new.email, 'Usuario'),
    new.email,
    coalesce(new.raw_user_meta_data->>'full_name', new.email, 'Usuario'),
    coalesce(new.raw_user_meta_data->>'role', 'Comercial'),
    coalesce((new.raw_user_meta_data->>'can_view_dashboard')::boolean, false)
  )
  on conflict (id) do update
  set name = coalesce(public.profiles.name, excluded.name),
      email = excluded.email,
      full_name = coalesce(public.profiles.full_name, excluded.full_name),
      role = coalesce(public.profiles.role, excluded.role),
      can_view_dashboard = public.profiles.can_view_dashboard or excluded.can_view_dashboard;

  return new;
end;
$$ language plpgsql security definer;

drop trigger if exists auth_users_create_profile on auth.users;
create trigger auth_users_create_profile
after insert on auth.users
for each row execute function create_profile_for_auth_user();

