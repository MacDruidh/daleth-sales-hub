create or replace function current_profile_role()
returns text as $$
  select coalesce(
    (
      select p.role
      from public.profiles p
      where p.id = auth.uid()
      limit 1
    ),
    ''
  );
$$ language sql stable security definer set search_path = public;

create or replace function can_write_crm()
returns boolean as $$
  select current_profile_role() in ('CEO', 'Comercial');
$$ language sql stable security definer set search_path = public;

create or replace function is_ceo()
returns boolean as $$
  select current_profile_role() = 'CEO';
$$ language sql stable security definer set search_path = public;

